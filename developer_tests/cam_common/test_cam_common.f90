! Test the CAM shared code used by cam-fv and cam-se.
!
! The expected numbers in the vertical math tests were generated by running
! the same calls through the original cam_common_code_mod (before it was split
! up), so they pin the behavior across the refactor.  Nothing here needs a
! model_mod, a namelist for the model, an ensemble or a CAM file: the grid is
! built by hand and every setting is passed in.

program test_cam_common

use types_mod,         only : r8, MISSING_R8, MISSING_I
use utilities_mod,     only : initialize_utilities, finalize_utilities
use location_mod,      only : VERTISLEVEL, VERTISHEIGHT, VERTISPRESSURE, VERTISSCALEHEIGHT
use cam_grid_mod,      only : cam_grid, init_grid_refs
use cam_vertical_mod,  only : build_heights, gph2gmh, vert_interp, check_good_levels, &
                              height_to_level, pressure_to_level, scale_height, &
                              build_cam_pressure_columns, std_atm_table_type, init_std_atm_table, &
                              free_std_atm_table, std_atm_pressure_to_height, &
                              std_atm_height_to_pressure, HIGH_TOP_TABLE, LOW_TOP_TABLE
use cam_vert_loc_mod,  only : cam_vert_config, set_vert_localization, init_sign_of_vert_units, &
                              init_discard_high_obs, init_damping_ramp_info, obs_too_high, &
                              free_vert_config

use test,              only : ok, plan, isrel, isabs, is

implicit none

integer, parameter :: NLEV = 5
real(r8), parameter :: TOL = 1.0e-12_r8   ! relative, see isrel

type(cam_grid) :: grid
real(r8) :: sp(1), pcol(NLEV,1), vt(NLEV), mbar(NLEV), hts(NLEV)

! output_flag = .false. keeps DART's start/finish banners off stdout.
call initialize_utilities('test_cam_common', output_flag=.false.)

call plan(61)

call make_grid(grid)
sp(1) = 98000.0_r8
vt    = (/230.0_r8, 250.0_r8, 270.0_r8, 285.0_r8, 290.0_r8/)
mbar  = (/28.9_r8, 28.9_r8, 28.0_r8, 27.0_r8, 26.0_r8/)

call test_grid_refs()
call test_pressure_columns()
call test_heights()
call test_gph2gmh()
call test_scale_height()
call test_interp_and_levels()
call test_std_atm()
call test_vert_config()
call test_configs_are_independent()

call finalize_utilities()

contains

!------------------------------------------------------------------
!> a 5 level grid with made up (but sensible) hybrid coefficients

subroutine make_grid(g)
type(cam_grid), intent(out) :: g
integer :: i

g%P0%nsize   = 1
allocate(g%P0%vals(1));   g%P0%vals(1) = 100000.0_r8
g%lev%nsize  = NLEV
allocate(g%lev%vals(NLEV)); g%lev%vals = (/ (real(i, r8), i=1, NLEV) /)
g%hyai%nsize = NLEV+1
allocate(g%hyai%vals(NLEV+1))
g%hyai%vals  = (/0.0004_r8, 0.003_r8, 0.004_r8, 0.002_r8, 0.0005_r8, 0.0_r8/)
g%hybi%nsize = NLEV+1
allocate(g%hybi%vals(NLEV+1))
g%hybi%vals  = (/0.0_r8, 0.1_r8, 0.4_r8, 0.7_r8, 0.9_r8, 1.0_r8/)
g%hyam%nsize = NLEV
allocate(g%hyam%vals(NLEV))
g%hyam%vals  = (/0.0017_r8, 0.0035_r8, 0.003_r8, 0.00125_r8, 0.00025_r8/)
g%hybm%nsize = NLEV
allocate(g%hybm%vals(NLEV))
g%hybm%vals  = (/0.05_r8, 0.25_r8, 0.55_r8, 0.8_r8, 0.95_r8/)

call init_grid_refs(g)

end subroutine make_grid

!------------------------------------------------------------------

subroutine test_grid_refs()

call isrel(grid%ref_surface_pressure, 100000.0_r8, TOL, 'grid: reference surface pressure is P0')
call isrel(grid%ref_model_top_pressure, 40.0_r8, TOL, 'grid: model top pressure is hyai(1)*P0')
call is(grid%ref_nlevels, NLEV,                     'grid: number of levels')

end subroutine test_grid_refs

!------------------------------------------------------------------

subroutine test_pressure_columns()

integer :: k
real(r8), parameter :: expected(NLEV) = (/ 5.0700000000000000E+03_r8, 2.4850000000000000E+04_r8, &
                                           5.4200000000000007E+04_r8, 7.8525000000000000E+04_r8, &
                                           9.3125000000000000E+04_r8 /)

call build_cam_pressure_columns(1, sp, NLEV, grid%ref_surface_pressure, &
                                grid%hyam%vals, grid%hybm%vals, pcol)
do k = 1, NLEV
   call isrel(pcol(k,1), expected(k), TOL, 'pressure column')
enddo

end subroutine test_pressure_columns

!------------------------------------------------------------------

subroutine test_heights()

integer :: k
real(r8), parameter :: expected(NLEV)  = (/ 2.2081082422382133E+04_r8, 1.0914511018161593E+04_r8, &
                                            4.9796176394791582E+03_r8, 1.9681974749622404E+03_r8, &
                                            5.3313449461732296E+02_r8 /)
real(r8), parameter :: expected_mbar(NLEV) = (/ 2.2565245093186168E+04_r8, 1.1373711480725369E+04_r8, &
                                                5.3262788159603560E+03_r8, 2.1518674069385152E+03_r8, &
                                                5.8252189298843666E+02_r8 /)

call build_heights(NLEV, sp(1), 100.0_r8, grid%hybi%vals(NLEV+1), pcol(:,1), vt, hts)
do k = 1, NLEV
   call isrel(hts(k), expected(k), TOL, 'build_heights: dry air gas constant')
enddo

call build_heights(NLEV, sp(1), 100.0_r8, grid%hybi%vals(NLEV+1), pcol(:,1), vt, hts, mbar=mbar)
do k = 1, NLEV
   call isrel(hts(k), expected_mbar(k), TOL, 'build_heights: variable gas constant')
enddo

end subroutine test_heights

!------------------------------------------------------------------

subroutine test_gph2gmh()

real(r8) :: h(2,2)
real(r8), parameter :: expected(4) = (/ 1.0006438038470908E+03_r8, 5.0063650986180637E+03_r8, &
                                        2.0072792871494741E+04_r8, 8.1057526603894265E+04_r8 /)

h = reshape((/ 1000.0_r8, 5000.0_r8, 20000.0_r8, 80000.0_r8 /), (/2,2/))
call gph2gmh(h, 40.0_r8)
call isrel(h(1,1), expected(1), TOL, 'gph2gmh: 1 km')
call isrel(h(2,1), expected(2), TOL, 'gph2gmh: 5 km')
call isrel(h(1,2), expected(3), TOL, 'gph2gmh: 20 km')
call isrel(h(2,2), expected(4), TOL, 'gph2gmh: 80 km')

end subroutine test_gph2gmh

!------------------------------------------------------------------

subroutine test_scale_height()

call isrel(scale_height(50000.0_r8, 98000.0_r8, .false.), 6.7294447324242579E-01_r8, TOL,&
          'scale_height: normalized by surface pressure')
call isrel(scale_height(50000.0_r8, 98000.0_r8, .true.), 1.0819778284410283E+01_r8, TOL,&
          'scale_height: not normalized is log(p)')
! exactly 0 has no relative scale, so this one is an absolute comparison
call isabs(scale_height(98000.0_r8, 98000.0_r8, .false.), 0.0_r8, TOL, &
          'scale_height: at the surface is 0')
call isrel(scale_height(0.0_r8, 98000.0_r8, .false.), MISSING_R8, TOL,&
          'scale_height: zero pressure is missing')

end subroutine test_scale_height

!------------------------------------------------------------------

subroutine test_interp_and_levels()

real(r8) :: out(3), fract
integer  :: l1, l2, st

call vert_interp(3, (/1.0_r8, 2.0_r8, 3.0_r8/), (/4.0_r8, 6.0_r8, 9.0_r8/), &
                 (/0.0_r8, 0.25_r8, 1.0_r8/), out)
call isrel(out(1), 1.0_r8, TOL, 'vert_interp: fraction 0 is the first level')
call isrel(out(2), 3.0_r8, TOL, 'vert_interp: fraction 0.25')
call isrel(out(3), 9.0_r8, TOL, 'vert_interp: fraction 1 is the second level')

call ok(.not. check_good_levels(0.5_r8, NLEV, l1, l2, fract), 'check_good_levels: above the top is bad')
call ok(check_good_levels(1.0_r8, NLEV, l1, l2, fract), 'check_good_levels: level 1 is good')
call is(l2, 2, 'check_good_levels: level 1 brackets 1,2')
call ok(check_good_levels(3.5_r8, NLEV, l1, l2, fract), 'check_good_levels: mid level is good')
call isrel(fract, 0.5_r8, TOL, 'check_good_levels: halfway')
call ok(check_good_levels(5.0_r8, NLEV, l1, l2, fract), 'check_good_levels: bottom level is good')
call is(l1, 4, 'check_good_levels: bottom level brackets 4,5')
call isrel(fract, 1.0_r8, TOL, 'check_good_levels: bottom is all of level 2')

call pressure_to_level(NLEV, pcol(:,1), 50000.0_r8, .false., l1, l2, fract, st)
call is(st, 0, 'pressure_to_level: in range status')
call isrel(fract, 8.5689948892674594E-01_r8, TOL, 'pressure_to_level: linear')
call pressure_to_level(NLEV, pcol(:,1), 50000.0_r8, .true., l1, l2, fract, st)
call isrel(fract, 8.9656898181734479E-01_r8, TOL, 'pressure_to_level: log scale')
call pressure_to_level(NLEV, pcol(:,1), 5.0_r8, .false., l1, l2, fract, st)
call is(st, 10, 'pressure_to_level: above the top gives status 10')

call height_to_level(NLEV, hts, 2000.0_r8, l1, l2, fract, st)
call is(st, 0, 'height_to_level: in range status')
call isrel(fract, 9.0322882654676762E-01_r8, TOL, 'height_to_level: fraction')
call height_to_level(NLEV, hts, 9.0e5_r8, l1, l2, fract, st)
call is(st, 11, 'height_to_level: above the top gives status 11')

end subroutine test_interp_and_levels

!------------------------------------------------------------------
!> two standard atmosphere tables to allow for low or high top models

subroutine test_std_atm()

type(std_atm_table_type) :: low, high
real(r8) :: p, hgt
integer  :: st

call is(init_std_atm_table(low,  grid%ref_model_top_pressure), LOW_TOP_TABLE,  'std_atm: low top table')
call is(init_std_atm_table(high, 1.0e-3_r8),                   HIGH_TOP_TABLE, 'std_atm: high top table')

p = std_atm_height_to_pressure(low, 9000.0_r8, st)
call isrel(p, 3.1075000000000000E+04_r8, TOL, 'std_atm: 9 km in pascals')

hgt = std_atm_pressure_to_height(low, 30000.0_r8, .false., st)
call ok(st == 0 .and. hgt > 9000.0_r8 .and. hgt < 10000.0_r8, 'std_atm: 300 hPa is between 9 and 10 km')

p = std_atm_height_to_pressure(low, 9.0e5_r8, st)
call is(st, 11, 'std_atm: height above the table gives status 11')

call free_std_atm_table(low)
call free_std_atm_table(high)

end subroutine test_std_atm

!------------------------------------------------------------------
!> the vertical localization settings, with no model_mod and no namelist

subroutine test_vert_config()

type(cam_vert_config) :: cfg
integer :: st

call set_vert_localization(cfg, 'PRESSURE')
call init_sign_of_vert_units(cfg)
call is(cfg%localization_type, VERTISPRESSURE, 'vert_config: localizing in pressure')
call ok(cfg%higher_is_smaller, 'vert_config: pressure gets smaller as you go up')

call init_discard_high_obs(cfg, grid, 2)
call ok(cfg%discarding_high_obs, 'vert_config: discarding is turned on')
call init_damping_ramp_info(cfg, grid, 3)
call ok(cfg%are_damping, 'vert_config: damping is turned on')
call isrel(cfg%ramp_end, 5.5300000000000007E+04_r8, TOL, 'vert_config: ramp end is level 3 in pascals')

call obs_too_high(cfg, 10.0_r8,     VERTISPRESSURE, st)
call is(st, 14, 'obs_too_high: very low pressure is too high')
call obs_too_high(cfg, 1.0e5_r8,    VERTISPRESSURE, st)
call is(st, 0,  'obs_too_high: surface pressure is fine')
call obs_too_high(cfg, 1.0_r8,      VERTISLEVEL,    st)
call is(st, 0,  'obs_too_high: level 1 is fine as the cutoff is 2 levels in pressure')
call obs_too_high(cfg, 1.0e6_r8,    VERTISHEIGHT,   st)
call is(st, 14, 'obs_too_high: very high height is too high')

call free_vert_config(cfg)

end subroutine test_vert_config

!------------------------------------------------------------------
!> No hidden module state: two configs set up differently do not interfere.

subroutine test_configs_are_independent()

type(cam_vert_config) :: in_pressure, in_height

call set_vert_localization(in_pressure, 'PRESSURE')
call set_vert_localization(in_height,   'HEIGHT')
call init_sign_of_vert_units(in_pressure)
call init_sign_of_vert_units(in_height)

call is(in_pressure%localization_type, VERTISPRESSURE, 'independent configs: first is still pressure')
call is(in_height%localization_type,   VERTISHEIGHT,   'independent configs: second is height')
call ok(in_pressure%higher_is_smaller .and. .not. in_height%higher_is_smaller, &
   'independent configs: sign of the vertical units differs')

end subroutine test_configs_are_independent

end program test_cam_common
