subroutine get_initial_condition(initial_time, x)
!----------------------------------------------------------------------
! Get initial conditions for all models
!----------------------------------------------------------------------

type(time_type), intent(out) :: initial_time
real(r8),        intent(out) :: x(:)

integer :: model_idx, start_idx, end_idx
logical :: time_set

time_set = .false.

do model_idx = 1, num_models
   start_idx = model_offsets(model_idx)
   end_idx = start_idx + model_sizes(model_idx) - 1
   
EOF

# Generate init conditions for each model
for model in "${MODELS[@]}"; do
  short_name="${MODEL_SHORT_NAMES[$model]}"
  flag=$(echo "$short_name" | tr '[:lower:]' '[:upper:]')
  
  cat >> "$OUTPUT_FILE" <<EOF
#ifdef USE_${flag}
   if (trim(model_names(model_idx)) == '${short_name}') then
      call ${short_name}_init_conditions(x(start_idx:end_idx))
      if (.not. time_set) then
         call ${short_name}_init_time(initial_time)
         time_set = .true.
      endif
   endif
#endif
EOF
done

cat >> "$OUTPUT_FILE" <<'EOF'
enddo

end subroutine get_initial_condition

