subroutine get_state_meta_data(index_in, location, var_type)
!----------------------------------------------------------------------
! Returns the location and type of a state variable
! Determines which model owns this index and calls appropriate routine
!----------------------------------------------------------------------

integer(i8),         intent(in)  :: index_in
type(location_type), intent(out) :: location
integer, optional,   intent(out) :: var_type

integer :: model_idx, i
integer(i8) :: local_index

! Find which model owns this state index
model_idx = -1
do i = 1, num_models
   if (index_in >= model_offsets(i) .and. &
       index_in < model_offsets(i) + model_sizes(i)) then
      model_idx = i
      local_index = index_in - model_offsets(i) + 1
      exit
   endif
enddo

if (model_idx == -1) then
   call error_handler(E_ERR, 'get_state_meta_data', &
        'Index not found in any model', source, revision, revdate)
endif

! Call the appropriate model's get_state_meta_data based on model name
EOF

# Generate select for get_state_meta_data
first_model=1
for model in "${MODELS[@]}"; do
  short_name="${MODEL_SHORT_NAMES[$model]}"
  flag=$(echo "$short_name" | tr '[:lower:]' '[:upper:]')
  
  cat >> "$OUTPUT_FILE" <<EOF
#ifdef USE_${flag}
if (trim(model_names(model_idx)) == '${short_name}') then
   call ${short_name}_get_state_meta_data(local_index, location, var_type)
   return
endif
#endif
EOF
done

cat >> "$OUTPUT_FILE" <<'EOF'

call error_handler(E_ERR, 'get_state_meta_data', &
     'Unknown model name', source, revision, revdate)

end subroutine get_state_meta_data

!======================================================================

function get_model_time_step()
!----------------------------------------------------------------------
! Returns the shortest time step from all models
!----------------------------------------------------------------------

type(time_type) :: get_model_time_step
type(time_type) :: model_time_step
logical :: first_model

first_model = .true.

EOF

# Generate time step comparison
for model in "${MODELS[@]}"; do
  short_name="${MODEL_SHORT_NAMES[$model]}"
  flag=$(echo "$short_name" | tr '[:lower:]' '[:upper:]')
  
  cat >> "$OUTPUT_FILE" <<EOF
#ifdef USE_${flag}
model_time_step = ${short_name}_shortest_time_between_assimilations()
if (first_model) then
   get_model_time_step = model_time_step
   first_model = .false.
else if (model_time_step < get_model_time_step) then
   get_model_time_step = model_time_step
endif
#endif
EOF
done

cat >> "$OUTPUT_FILE" <<'EOF'

end function get_model_time_step

!======================================================================

function get_closest_state_time_to(model_time, given_time)
!----------------------------------------------------------------------
! Returns the time closest to the given time that the model can reach
!----------------------------------------------------------------------

type(time_type) :: get_closest_state_time_to
type(time_type), intent(in) :: model_time, given_time

type(time_type) :: time_step

time_step = get_model_time_step()

if(model_time > given_time) then
   get_closest_state_time_to = model_time
   return
endif

get_closest_state_time_to = model_time

do while((time_step + 2*get_closest_state_time_to) < 2*given_time)
   get_closest_state_time_to = get_closest_state_time_to + time_step
enddo

end function get_closest_state_time_to

