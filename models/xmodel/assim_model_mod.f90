!======================================================================

subroutine static_init_assim_model()
!----------------------------------------------------------------------
! Initializes the multi-model assim_model
! Calls static_init_model for each component model
!----------------------------------------------------------------------

integer :: i, model_idx

! only execute this code once, even if called multiple times.
if (module_initialized) return

call register_module(source, revision, revdate)

module_initialized = .true.

! Count how many models are enabled
num_models = 0
#ifdef USE_CAMFV
num_models = num_models + 1
#endif
#ifdef USE_WRF
num_models = num_models + 1
#endif

if (num_models == 0) then
   call error_handler(E_ERR, 'static_init_assim_model', &
        'No models enabled. Define at least one USE_* preprocessor flag', &
        source, revision, revdate)
endif

allocate(model_sizes(num_models))
allocate(model_offsets(num_models))
allocate(model_names(num_models))

! Initialize each model and get its size
model_idx = 0
total_model_size = 0

#ifdef USE_CAMFV
model_idx = model_idx + 1
model_names(model_idx) = 'camfv'
call camfv_static_init_model()
model_sizes(model_idx) = camfv_get_model_size()
model_offsets(model_idx) = total_model_size + 1
total_model_size = total_model_size + model_sizes(model_idx)
write(*, *) 'Model ', model_idx, ': ', trim(model_names(model_idx)), &
            ' Size: ', model_sizes(model_idx), ' Offset: ', model_offsets(model_idx)
#endif

#ifdef USE_WRF
model_idx = model_idx + 1
model_names(model_idx) = 'wrf'
call wrf_static_init_model()
model_sizes(model_idx) = wrf_get_model_size()
model_offsets(model_idx) = total_model_size + 1
total_model_size = total_model_size + model_sizes(model_idx)
write(*, *) 'Model ', model_idx, ': ', trim(model_names(model_idx)), &
            ' Size: ', model_sizes(model_idx), ' Offset: ', model_offsets(model_idx)
#endif

write(*, *) 'Multi-model initialization complete'
write(*, *) 'Number of models: ', num_models
write(*, *) 'Total state size: ', total_model_size

end subroutine static_init_assim_model

