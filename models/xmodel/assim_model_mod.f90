subroutine find_model_for_index(index_in, model_idx, local_index)
!----------------------------------------------------------------------
! Determines which model owns a given state index
! Returns the model index and the local index within that model
!----------------------------------------------------------------------

integer(i8), intent(in)  :: index_in
integer,     intent(out) :: model_idx
integer(i8), intent(out) :: local_index

integer :: i

do i = 1, num_models
   if (index_in >= model_offsets(i) .and. &
       index_in < model_offsets(i) + model_sizes(i)) then
      model_idx = i
      local_index = index_in - model_offsets(i) + 1
      return
   endif
enddo

call error_handler(E_ERR, 'find_model_for_index', &
     'Index not found in any model', source, revision, revdate)

end subroutine find_model_for_index

