subroutine get_state_meta_data(index_in, location, var_type)
!----------------------------------------------------------------------
! Returns the location and type of a state variable
! Determines which model owns this index and calls appropriate routine
!----------------------------------------------------------------------

integer(i8),         intent(in)  :: index_in
type(location_type), intent(out) :: location
integer,             intent(out) :: var_type

integer :: model_idx, local_index

! Find which model owns this state index
call find_model_for_index(index_in, model_idx, local_index)

! Call the appropriate model's get_state_meta_data
select case (model_idx)
#ifdef USE_CAMFV
   case (1)  ! Assuming camfv is model 1 if defined
      call camfv_get_state_meta_data(local_index, location, var_type)
#endif
#ifdef USE_WRF
   case (2)  ! Assuming wrf is model 2 if both defined, or 1 if only wrf
      call wrf_get_state_meta_data(local_index, location, var_type)
#endif
   case default
      call error_handler(E_ERR, 'get_state_meta_data', &
           'Invalid model index', source, revision, revdate)
end select

end subroutine get_state_meta_data

!======================================================================

function get_model_time_step()
!----------------------------------------------------------------------
! Returns the shortest time step from all models
!----------------------------------------------------------------------

type(time_type) :: get_model_time_step
type(time_type) :: model_time_step

#ifdef USE_CAMFV
get_model_time_step = camfv_shortest_time_between_assimilations()
#endif

#ifdef USE_WRF
model_time_step = wrf_shortest_time_between_assimilations()
#ifdef USE_CAMFV
if (model_time_step < get_model_time_step) then
   get_model_time_step = model_time_step
endif
#else
get_model_time_step = model_time_step
#endif
#endif

end function get_model_time_step

!======================================================================

function get_closest_state_time_to(model_time, given_time)
!----------------------------------------------------------------------
! Returns the time closest to the given time that the model can reach
!----------------------------------------------------------------------

type(time_type) :: get_closest_state_time_to
type(time_type), intent(in) :: model_time, given_time

type(time_type) :: time_step

time_step = get_model_time_step()

if(model_time > given_time) then
   get_closest_state_time_to = model_time
   return
endif

get_closest_state_time_to = model_time

do while((time_step + 2*get_closest_state_time_to) < 2*given_time)
   get_closest_state_time_to = get_closest_state_time_to + time_step
enddo

end function get_closest_state_time_to

!======================================================================

subroutine get_initial_condition(initial_time, x)
!----------------------------------------------------------------------
! Get initial conditions for all models
!----------------------------------------------------------------------

type(time_type), intent(out) :: initial_time
real(r8),        intent(out) :: x(:)

integer :: model_idx, start_idx, end_idx

! Get initial conditions from each model
#ifdef USE_CAMFV
start_idx = model_offsets(1)
end_idx = start_idx + model_sizes(1) - 1
call camfv_init_conditions(x(start_idx:end_idx))
call camfv_init_time(initial_time)
#endif

#ifdef USE_WRF
! Find WRF model index based on what's defined
#ifdef USE_CAMFV
model_idx = 2
#else
model_idx = 1
#endif
start_idx = model_offsets(model_idx)
end_idx = start_idx + model_sizes(model_idx) - 1
call wrf_init_conditions(x(start_idx:end_idx))
! Override time if WRF time is earlier? For now just use first model's time
#endif

end subroutine get_initial_condition

!======================================================================

subroutine end_assim_model()
!--------------------------------------------------------------------
! Closes down assim_model - calls end_model for each component
!--------------------------------------------------------------------

#ifdef USE_CAMFV
call camfv_end_model()
#endif

#ifdef USE_WRF
call wrf_end_model()
#endif

if (allocated(model_sizes)) deallocate(model_sizes)
if (allocated(model_offsets)) deallocate(model_offsets)
if (allocated(model_names)) deallocate(model_names)

end subroutine end_assim_model

